const fs = require('fs');
const path = require('path');
const JSZip = require('jszip');

const publicBooksDir = path.join(__dirname, '..', 'public', 'books');
const assetsBooksDir = path.join(__dirname, '..', 'assets', 'books');

if (!fs.existsSync(publicBooksDir)) fs.mkdirSync(publicBooksDir, { recursive: true });
if (!fs.existsSync(assetsBooksDir)) fs.mkdirSync(assetsBooksDir, { recursive: true });

async function createEpub({ id, title, author, language, chapters }) {
  const zip = new JSZip();

  // 1. mimetype (uncompressed)
  zip.file('mimetype', 'application/epub+zip', { compression: 'STORE' });

  // 2. META-INF/container.xml
  zip.file(
    'META-INF/container.xml',
    `<?xml version="1.0" encoding="UTF-8"?>
<container version="1.0" xmlns="urn:oasis:names:tc:opendocument:xmlns:container">
  <rootfiles>
    <rootfile full-path="OEBPS/content.opf" media-type="application/oebps-package+xml"/>
  </rootfiles>
</container>`
  );

  // Manifest items and spine
  const manifestItems = [
    `<item id="ncx" href="toc.ncx" media-type="application/x-dtbncx+xml"/>`,
  ];
  const spineItems = [];
  const navPoints = [];

  chapters.forEach((chap, idx) => {
    const filename = `chap_${idx + 1}.xhtml`;
    manifestItems.push(`<item id="chap${idx + 1}" href="${filename}" media-type="application/xhtml+xml"/>`);
    spineItems.push(`<itemref idref="chap${idx + 1}"/>`);
    navPoints.push(`
    <navPoint id="navpoint-${idx + 1}" playOrder="${idx + 1}">
      <navLabel><text>${chap.title}</text></navLabel>
      <content src="${filename}"/>
    </navPoint>`);

    // Create chapter XHTML
    const xhtml = `<?xml version="1.0" encoding="utf-8"?>
<!DOCTYPE html PUBLIC "-//W3C//DTD XHTML 1.1//EN" "http://www.w3.org/TR/xhtml11/DTD/xhtml11.dtd">
<html xmlns="http://www.w3.org/1999/xhtml" lang="${language}">
<head>
  <title>${chap.title}</title>
  <style>
    body { font-family: sans-serif; line-height: 1.8; padding: 1.5em; }
    h1 { color: #8A6517; border-bottom: 2px solid #E5BA58; padding-bottom: 0.3em; margin-bottom: 0.8em; }
    h2 { color: #8A6517; margin-top: 1em; }
    p { margin-bottom: 1em; text-align: justify; }
    .verse { font-style: italic; background: rgba(229,186,88,0.08); padding: 1em; border-left: 4px solid #E5BA58; margin: 1.2em 0; border-radius: 4px; }
  </style>
</head>
<body>
  <h1>${chap.title}</h1>
  ${chap.content}
</body>
</html>`;
    zip.file(`OEBPS/${filename}`, xhtml);
  });

  // content.opf
  const opf = `<?xml version="1.0" encoding="UTF-8"?>
<package xmlns="http://www.idpf.org/2007/opf" unique-identifier="BookID" version="2.0">
  <metadata xmlns:dc="http://purl.org/dc/elements/1.1/" xmlns:opf="http://www.idpf.org/2007/opf">
    <dc:title>${title}</dc:title>
    <dc:creator opf:role="aut">${author}</dc:creator>
    <dc:language>${language}</dc:language>
    <dc:identifier id="BookID">urn:readora:${id}</dc:identifier>
  </metadata>
  <manifest>
    ${manifestItems.join('\n    ')}
  </manifest>
  <spine toc="ncx">
    ${spineItems.join('\n    ')}
  </spine>
</package>`;
  zip.file('OEBPS/content.opf', opf);

  // toc.ncx
  const ncx = `<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE ncx PUBLIC "-//NISO//DTD ncx 2005-1//EN" "http://www.daisy.org/z3986/2005/ncx-2005-1.dtd">
<ncx xmlns="http://www.daisy.org/z3986/2005/ncx/" version="2005-1">
  <head>
    <meta name="dtb:uid" content="urn:readora:${id}"/>
  </head>
  <docTitle>
    <text>${title}</text>
  </docTitle>
  <navMap>
    ${navPoints.join('\n')}
  </navMap>
</ncx>`;
  zip.file('OEBPS/toc.ncx', ncx);

  const arrayBuffer = await zip.generateAsync({ type: 'nodebuffer', compression: 'DEFLATE' });
  const filename = `${id}.epub`;
  fs.writeFileSync(path.join(publicBooksDir, filename), arrayBuffer);
  fs.writeFileSync(path.join(assetsBooksDir, filename), arrayBuffer);
  console.log(`Generated full multi-chapter EPUB for ${title} (${arrayBuffer.length} bytes, ${chapters.length} chapters)`);
}

